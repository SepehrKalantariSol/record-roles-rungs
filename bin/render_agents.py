#!/usr/bin/env python3
"""render_agents.py: render agent definitions from role files plus tool grants.

    python3 bin/render_agents.py --target record=<dir> [--target product=<dir>] [--check]

A role file (roles/<role>.md) says what the role reads, what it produces and
what it must not do. That is intent. roles/toolbelt.json says which tools the
role may use and which repositories its definition goes into. That is the part
a tool layer can enforce. Neither is complete alone, so this script joins them:
one definition, rendered into every repository that needs it.

Every output is stamped as generated. A file in a target directory without the
stamp is never overwritten, because a person wrote it. With --check nothing is
written, and the script fails if any output is missing or out of date.

Standard library only.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / "roles"
GRANTS = ROLES / "toolbelt.json"
MARK = "<!-- generated by bin/render_agents.py"
STAMP = MARK + " from roles/{role}.md and roles/toolbelt.json. Edit those, not this file. -->"


def load_grants():
    data = json.loads(GRANTS.read_text(encoding="utf-8"))
    grants = data["roles"]
    files = {path.stem for path in ROLES.glob("*.md")}
    no_file = sorted(set(grants) - files)
    no_grant = sorted(files - set(grants))
    if no_file or no_grant:
        raise SystemExit("render_agents: roles and grants disagree. "
                         f"Granted but no role file: {no_file or 'none'}. "
                         f"Role file but no grant: {no_grant or 'none'}.")
    return data["repos"], grants


def summary(text):
    """The first non-empty line after the title."""
    for line in text.splitlines()[1:]:
        if line.strip():
            return line.strip()
    return ""


def render(role, grant, body):
    return ("---\n"
            f"name: {role}\n"
            f"description: {summary(body)}\n"
            f"tools: {', '.join(grant['tools'])}\n"
            "---\n"
            f"{STAMP.format(role=role)}\n\n"
            f"{body.rstrip()}\n")


def main(argv=None):
    parser = argparse.ArgumentParser(prog="render_agents.py",
                                     description="Render agent definitions.")
    parser.add_argument("--target", action="append", required=True, metavar="REPO=DIR",
                        help="where one repository keeps its agent definitions")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; fail if any output is missing or stale")
    args = parser.parse_args(argv)

    repos, grants = load_grants()
    targets = {}
    for item in args.target:
        repo, sep, directory = item.partition("=")
        if not sep or repo not in repos:
            raise SystemExit(f"render_agents: --target takes REPO=DIR, with REPO one "
                             f"of: {', '.join(sorted(repos))}")
        targets[repo] = Path(directory)

    problems, written = [], 0
    for role in sorted(grants):
        grant = grants[role]
        text = render(role, grant, (ROLES / f"{role}.md").read_text(encoding="utf-8"))
        for repo in grant["repos"]:
            if repo not in targets:
                continue
            out = targets[repo] / f"{role}.md"
            existing = out.read_text(encoding="utf-8") if out.exists() else None
            if existing is not None and MARK not in existing:
                problems.append(f"{out} was written by hand; not overwriting it")
                continue
            if args.check:
                if existing != text:
                    problems.append(f"{out} is missing or out of date")
                continue
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            written += 1

    for problem in problems:
        print(f"render_agents: {problem}", file=sys.stderr)
    if not args.check:
        print(f"render_agents: wrote {written} file(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
